"""Small integration example; helpers can also be imported separately."""
import argparse
import time
import cv2
from camera import open_camera, read_frame, close_camera, show_frame
from vision import create_detector, detect_tags, select_tag, load_calibration, estimate_pose, draw_feedback
from control import tracking_rates
from motors import connect_arduino, arm_motors, send_velocity, stop_motors, disconnect_arduino


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--camera', default='0', help='Camera index or stream URL')
    parser.add_argument('--width', type=int, default=1280)
    parser.add_argument('--height', type=int, default=720)
    parser.add_argument('--family', default='36h11')
    parser.add_argument('--tag-id', type=int, default=0)
    parser.add_argument('--tag-size', type=float, help='Black square edge in meters')
    parser.add_argument('--calibration', help='JSON generated by calibrate.py')
    parser.add_argument('--port', help='COM3, /dev/ttyACM0, etc.')
    parser.add_argument('--motors', action='store_true', help='Allow manual arming with A')
    parser.add_argument('--zero-confirmed', action='store_true', help='Mount centered before board reset')
    parser.add_argument('--pan-direction', type=int, choices=[-1, 1], default=1)
    parser.add_argument('--tilt-direction', type=int, choices=[-1, 1], default=1)
    args = parser.parse_args()
    if args.motors and (not args.port or not args.zero_confirmed):
        parser.error('--motors requires --port and --zero-confirmed; see README')
    if bool(args.calibration) != (args.tag_size is not None):
        parser.error('Provide both --calibration and --tag-size for metric XYZ')
    if args.tag_size is not None and args.tag_size <= 0:
        parser.error('--tag-size must be positive')
    calibration = load_calibration(args.calibration) if args.calibration else None
    detector = create_detector(args.family)
    camera = connection = None
    tracking = False
    last_command = 0.0
    message = 'Preview only | A: tracking | Space: stop | Q: quit'
    try:
        camera = open_camera(int(args.camera) if args.camera.isdigit() else args.camera,
                             args.width, args.height)
        if args.motors:
            connection = connect_arduino(args.port)
        while True:
            frame = read_frame(camera)
            h, w = frame.shape[:2]
            if calibration and (w, h) != (calibration.width, calibration.height):
                raise ValueError('Capture resolution differs from calibration; recalibrate or change resolution')
            tags = detect_tags(frame, detector)
            target = select_tag(tags, args.tag_id)
            pose = estimate_pose(target.corners, args.tag_size, calibration) if target and calibration else None
            now = time.monotonic()
            if tracking and target is None:
                stop_motors(connection)
                tracking = False
                message = 'Target lost: stopped. A to resume after reacquiring.'
            if tracking and now - last_command >= .05:
                pan, tilt = tracking_rates(target.center, (w, h), args.pan_direction, args.tilt_direction)
                send_velocity(connection, pan, tilt)
                last_command = now
                message = f'Tracking ID {args.tag_id} | pan={pan:+.2f} tilt={tilt:+.2f} deg/s'
            view = draw_feedback(frame, tags, args.tag_id, pose, calibration, message)
            key = show_frame(view)
            if key == ord('q') or cv2.getWindowProperty('AprilTag camera', cv2.WND_PROP_VISIBLE) < 1:
                break
            if key == ord(' '):
                if connection:
                    stop_motors(connection)
                tracking = False
                message = 'Stopped; holding position. A to resume.'
            elif key == ord('a'):
                if tracking:
                    stop_motors(connection)
                    tracking = False
                    message = 'Tracking paused.'
                elif connection and target:
                    arm_motors(connection)
                    tracking = True
                    last_command = 0
                else:
                    message = 'Need --motors, Arduino connection, and visible target to arm.'
    finally:
        try:
            disconnect_arduino(connection)
        finally:
            close_camera(camera)
            cv2.destroyAllWindows()


if __name__ == '__main__':
    main()
